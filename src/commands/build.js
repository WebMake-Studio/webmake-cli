'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ui = require('../ui');
const { c, log } = ui;
const { resolveSettings } = require('../config');
const { loadRuleset, classify, WEBMAKE_FILES } = require('../detect');
const { WebMakeError } = require('../errors');
const { displayPath, formatBytes, plural } = require('../util');

function toNetlify(rule) {
  if (rule.unsupported || !rule.to) return null;
  if (rule.style === 'netlify') return { from: rule.from, to: rule.to };
  if (rule.style === 'firebase') {
    const from = rule.from.replace(/\*\*$/, '*');
    return /[{}?]/.test(from) || (from.match(/\*/g) || []).length > 1 || (from.includes('*') && !from.endsWith('/*') && from !== '*')
      ? null
      : { from: from === '*' ? '/*' : from, to: rule.to };
  }
  if (rule.style === 'vercel') {
    if (rule.from === '/(.*)') return { from: '/*', to: rule.to.replace(/\$1/g, ':splat') };
    const m = /^(.*)\/:(\w+)\*$/.exec(rule.from);
    if (m) return { from: `${m[1]}/*`, to: rule.to.replace(new RegExp(`:${m[2]}[*+]?`, 'g'), ':splat') };
    return /[()*+?\\^$|{}[\]]/.test(rule.from) || /\$\d/.test(rule.to) ? null : { from: rule.from, to: rule.to };
  }
  return null;
}

function headerPattern(h) {
  if (h.style === 'netlify') return h.pattern;
  const fake = { style: h.style, from: h.pattern, to: '/x', unsupported: null };
  const converted = toNetlify(fake);
  return converted ? converted.from : null;
}

function buildRedirectsFile(ruleset) {
  const lines = ['# Generated by WebMake CLI (webmake build) - do not edit by hand.'];
  const skipped = [];
  let exported = 0;
  for (const rule of ruleset.rules) {
    const conv = toNetlify(rule);
    if (!conv) { skipped.push(rule); continue; }
    const query = Object.entries(rule.query).map(([k, v]) => `${k}=${v}`).join(' ');
    lines.push([conv.from, query, conv.to, `${rule.status}${rule.force ? '!' : ''}`].filter(Boolean).join(' '));
    exported++;
  }
  return { text: `${lines.join('\n')}\n`, exported, skipped };
}

function buildHeadersFile(ruleset) {
  const lines = ['# Generated by WebMake CLI (webmake build) - do not edit by hand.'];
  const skipped = [];
  let exported = 0;
  for (const h of ruleset.headers) {
    const pattern = headerPattern(h);
    if (!pattern || !Object.keys(h.values).length) { skipped.push(h); continue; }
    lines.push(pattern);
    for (const [k, v] of Object.entries(h.values)) lines.push(`  ${k}: ${v}`);
    exported++;
  }
  return { text: `${lines.join('\n')}\n`, exported, skipped };
}

function assertSafeOutput({ cwd, root, out, force }) {
  const inside = (parent, child) => child === parent || child.startsWith(parent + path.sep);
  if (out === root) {
    throw new WebMakeError('The output folder is the same as the source folder.', {
      hint: 'Set a different "out" in webmake.dev (for example out: \'./dist\') or pass --out dist.',
    });
  }
  if (out === path.parse(out).root || out === os.homedir()) {
    throw new WebMakeError(`Refusing to use ${out} as output folder.`, { hint: 'Choose a dedicated folder such as ./dist.' });
  }
  if (inside(out, root) || inside(out, cwd)) {
    throw new WebMakeError('The output folder contains your source folder or project folder.', {
      hint: 'Choose a separate folder such as ./dist so nothing important gets overwritten.',
    });
  }
  if (!inside(cwd, out) && !force) {
    throw new WebMakeError(`The output folder is outside the current directory (${out}).`, { hint: 'Use --force if this is really what you want.' });
  }
}

async function build({ flags, positionals, cwd }) {
  if (positionals[0]) flags.dir = positionals[0];
  const started = Date.now();
  const settings = resolveSettings({ cwd, flags });
  ui.setQuiet(settings.quiet);
  const { root, out } = settings;

  let st = null;
  try { st = fs.statSync(root); } catch { }
  if (!st || !st.isDirectory()) {
    throw new WebMakeError(`Directory not found: ${displayPath(cwd, root)}`, { hint: 'Pass --dir <folder> or run the command from your project folder.' });
  }
  assertSafeOutput({ cwd, root, out, force: !!flags.force });

  ui.printBanner();
  for (const w of settings.warnings) log.warn(w);

  const ruleset = loadRuleset(settings);
  for (const w of ruleset.warnings) log.warn(w);

  if (flags.clean !== false) fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });

  let files = 0;
  let bytes = 0;
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (abs === out) continue;
      let isDir = entry.isDirectory();
      let isFile = entry.isFile();
      if (entry.isSymbolicLink()) {
        let target = null;
        try { target = fs.statSync(abs); } catch { }
        if (!target) continue;
        if (target.isDirectory()) { log.warn(`Symbolic link to a folder skipped: ${displayPath(cwd, abs)}`); continue; }
        isFile = target.isFile();
        isDir = false;
      }
      if (isDir) {
        if (entry.name === 'node_modules') continue;
        if (entry.name.startsWith('.') && entry.name !== '.well-known') continue;
        walk(abs);
      } else if (isFile) {
        const lower = entry.name.toLowerCase();
        if (entry.name.startsWith('.') && lower !== '.htaccess') continue;
        if (WEBMAKE_FILES.includes(lower)) continue;
        const type = classify(entry.name);
        if (type === 'redirects' || type === 'headers') continue;
        const dest = path.join(out, path.relative(root, abs));
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.copyFileSync(abs, dest);
        files++;
        bytes += fs.statSync(dest).size;
      }
    }
  };
  walk(root);

  const redirects = buildRedirectsFile(ruleset);
  const headers = buildHeadersFile(ruleset);
  if (redirects.exported) fs.writeFileSync(path.join(out, '_redirects'), redirects.text);
  if (headers.exported) fs.writeFileSync(path.join(out, '_headers'), headers.text);

  const label = (t) => c.muted(t.padEnd(9));
  log.success(`${c.bold('Built')} ${plural(files, 'file')} (${formatBytes(bytes)}) in ${Date.now() - started} ms`);
  log.raw('');
  log.raw(`  ${c.brand('➜')}  ${label('Source')} ${displayPath(cwd, root)}`);
  log.raw(`  ${c.brand('➜')}  ${label('Output')} ${displayPath(cwd, out)}`);
  log.raw(`  ${c.brand('➜')}  ${label('Routing')} ${redirects.exported ? `${plural(redirects.exported, 'rule')} → _redirects` : c.muted('no redirect rules')}${headers.exported ? ` · ${plural(headers.exported, 'header block')} → _headers` : ''}`);
  for (const r of redirects.skipped) log.warn(`${r.origin}: not exported to _redirects (${r.unsupported || 'syntax cannot be expressed in _redirects'})`);
  for (const h of headers.skipped) log.warn(`${h.origin}: headers not exported to _headers (pattern cannot be expressed)`);
  log.raw('');
}

module.exports = { build, toNetlify, buildRedirectsFile, buildHeadersFile };
